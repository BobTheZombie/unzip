#!/usr/bin/env python3
"""Regenerate immutable IEEE CRC-32 slicing-by-eight tables."""
from pathlib import Path
t = []
for i in range(256):
    c = i
    for _ in range(8):
        c = (c >> 1) ^ (0xedb88320 if c & 1 else 0)
    t.append(c)
tables = [t]
for _ in range(7):
    tables.append([(c >> 8) ^ t[c & 255] for c in tables[-1]])
s = '/* IEEE CRC-32 slicing-by-eight tables generated by modern/gen-crc.py. */\nstatic const uint32_t uz_crc_table[8][256] = {\n'
for tab in tables:
    s += ' {\n' + ''.join('  ' + ', '.join('0x%08xu' % x for x in tab[i:i+8]) + ',\n' for i in range(0, 256, 8)) + ' },\n'
s += '};\n'
Path(__file__).with_name('crc-table.h').write_text(s)
